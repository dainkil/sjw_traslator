package dev.sjw.common.routing;

/**
 * 난이도 티어 (§5.1). <b>난이도 축이지 모델 축이 아니다</b> — 어느 모델로 갈지는
 * {@link ModelAllocator}가 quota를 보고 따로 정한다 (ADR-010).
 *
 * <p>이 분리가 필요한 이유는 M4-S1 실측이다: 무료 티어에서 모델 간 차이는 단가(전부 0)가 아니라
 * quota이고, 상위 모델(3.5-flash)의 quota 몫은 전체의 3.8%뿐이다. 난이도를 모델에 1:1로 묶으면
 * 상위 티어 수요가 quota를 8배 초과해 배치가 그 티어에서 정체된다 (docs/benchmarks.md).
 */
public enum Tier {
    /** 엔티티 0개 + 정형문 구조 표지 — 최저 난이도. 실측 13.02% */
    T0,
    /** 기본. 위아래 어디에도 해당하지 않는 문장 전부. 실측 85.15% */
    T1,
    /** 동명이인 모호 — KB가 후보를 줬고 문맥으로 골라야 한다. 실측 1.83% */
    T2
}
